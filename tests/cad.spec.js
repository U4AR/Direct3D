import {test,expect} from "@playwright/test";
test("full device CAD: sketch context, exact STEP, history, local recording and recovery",async({page})=>{
 test.setTimeout(120000);
 const errors=[],cadBuildRequests=[];
 page.on("pageerror",e=>errors.push(e.message));
 page.on("request",r=>{if(r.url().includes("/api/cad/build"))cadBuildRequests.push(r.url());});
 await page.goto("http://localhost:5173/");
 await page.locator("#demo").click();
 await page.locator("#description").fill("A 40 by 30 by 20 millimetre block");
 await page.locator("#description-form button").click();
 await page.locator("#workspace-full-cad").click();
 await page.locator("#cad-context-toggle").click();
 await expect(page.locator("#cad-context-transcript")).toContainText("40 by 30 by 20");
 await expect(page.locator("#cad-sketch-reference")).toHaveAttribute("src",/^data:image/);
 await page.locator("#cad-context-toggle").click();
 const f=page.frameLocator('iframe[title="Full parametric CAD workspace"]');
 await f.getByLabel("Project name").fill("CAD integration test");
 await f.getByRole("button",{name:"Create project",exact:true}).click();
 await f.getByRole("button",{name:/^Box \(B\)/}).click();
 const inspector=f.getByRole("region",{name:"Feature inspector"});
 for(const [label,value] of [["Width (X)","40"],["Depth (Y)","30"],["Height (Z)","20"]])await inspector.getByLabel(label).fill(value);
 await inspector.getByRole("button",{name:/^Create/}).click();
 await expect(inspector).toHaveCount(0);
 const bodyCount=n=>f.getByRole("group",{name:"Workspace status"}).getByLabel(new RegExp(` · \\d+ features? · ${n} ${n===1?"body":"bodies"}\\. Sync `));
 await expect(bodyCount(1)).toBeVisible({timeout:30000});
 await f.getByRole("button",{name:"Undo",exact:true}).click();
 await expect(bodyCount(0)).toBeVisible();
 await f.getByRole("button",{name:"Redo",exact:true}).click();
 await expect(bodyCount(1)).toBeVisible();
 await expect(f.locator(".save-state")).toHaveAttribute("title",/Saved on this device/);
 const menu=f.locator("details.file-menu");await menu.locator("summary").click();
 const downloading=page.waitForEvent("download");
 await menu.getByRole("button",{name:/Export STEP/}).click();
 const file=await downloading,chunks=[];for await(const c of await file.createReadStream())chunks.push(c);
 const step=Buffer.concat(chunks).toString("utf8");expect(step).toContain("ISO-10303-21");expect(step).toContain("SI_UNIT(.MILLI.,.METRE.)");
 const points=[...step.matchAll(/CARTESIAN_POINT\('[^']*',\s*\(([^)]*)\)\)/g)].map(m=>m[1].split(",").map(Number));
 expect(points.length).toBeGreaterThan(0);
 for(const [axis,length] of [40,30,20].entries())expect(Math.max(...points.map(p=>p[axis]))-Math.min(...points.map(p=>p[axis]))).toBeCloseTo(length,4);
 await file.saveAs("test-results/cad-block.step");
 await page.locator("#cad-back").click();await expect(page.locator("#geometry-count")).toContainText("15 strokes");
 await page.reload();await page.locator("#workspace-full-cad").click();
 await expect(bodyCount(1)).toBeVisible({timeout:30000});
 const saved=await page.evaluate(async()=>{
  const db=await new Promise((res,rej)=>{const q=indexedDB.open("draw3d-studio",1);q.onsuccess=()=>res(q.result);q.onerror=()=>rej(q.error);});
  const rows=await new Promise(res=>{const q=db.transaction("assets").objectStore("assets").getAll();q.onsuccess=()=>res(q.result);});
  return Promise.all(rows.filter(a=>a.name.startsWith("cad/revisions/")).map(async a=>JSON.parse(await a.blob.text())));
 });
 expect(saved.some(d=>d.name==="CAD integration test" && d.featureOrder?.length===1 && d.commandLog?.length>0)).toBeTruthy();
 await page.locator("#cad-context-toggle").click();
 const exported=page.waitForEvent("download");await page.locator("#cad-context-export").click();
 const contextChunks=[];for await(const c of await (await exported).createReadStream())contextChunks.push(c);
 const context=JSON.parse(Buffer.concat(contextChunks).toString("utf8"));
 expect(context.cadDocument.name).toBe("CAD integration test");expect(context.cadDocument.featureOrder).toHaveLength(1);
 expect(context.strokes).toHaveLength(15);expect(context.transcripts.at(-1).text).toContain("40 by 30");
 expect(cadBuildRequests).toEqual([]);expect(errors).toEqual([]);
 await page.screenshot({path:"test-results/full-cad.png"});
});
